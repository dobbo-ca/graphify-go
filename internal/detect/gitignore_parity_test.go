func TestAncestorCeilingRules(t *testing.T) {
	// invalid empty .git is not a ceiling
	outer := resolved(t)
	t.Setenv("HOME", outer)
	mustWrite(t, filepath.Join(outer, "mid", ".gitignore"), "*.gen.py\n")
	if err := os.MkdirAll(filepath.Join(outer, "mid", ".git"), 0o755); err != nil {
		t.Fatal(err)
	}
	mustWrite(t, filepath.Join(outer, "mid", "sub", "a.gen.py"), "x")
	mustWrite(t, filepath.Join(outer, "mid", "sub", "b.go"), "x")
	got := collected(t, filepath.Join(outer, "mid", "sub"))
	if !got["a.gen.py"] || !got["b.go"] {
		t.Errorf("empty .git must not be a ceiling: %v", got)
	}

	// .git above HOME does not count
	top := resolved(t)
	mkGit(t, top)
	mustWrite(t, filepath.Join(top, ".gitignore"), "*.gen.py\n")
	home := filepath.Join(top, "home")
	t.Setenv("HOME", home)
	mustWrite(t, filepath.Join(home, "proj", "a.gen.py"), "x")
	got = collected(t, filepath.Join(home, "proj"))
	if !got["a.gen.py"] {
		t.Errorf(".git above HOME must not count: %v", got)
	}

	// .git file with gitdir: is a ceiling, info/exclude via commondir
	wt := resolved(t)
	t.Setenv("HOME", filepath.Join(wt, "nohome"))
	common := filepath.Join(wt, "common")
	gd := filepath.Join(common, "worktrees", "w")
	mustWrite(t, filepath.Join(gd, "commondir"), "../..\n")
	mustWrite(t, filepath.Join(common, "info", "exclude"), "*.hid.py\n")
	repo := filepath.Join(wt, "repo")
	mustWrite(t, filepath.Join(repo, ".git"), "gitdir: "+gd+"\n")
	mustWrite(t, filepath.Join(repo, "sub", "a.hid.py"), "x")
	mustWrite(t, filepath.Join(repo, "sub", "b.go"), "x")
	got = collected(t, filepath.Join(repo, "sub"))
	if got["a.hid.py"] || !got["b.go"] {
		t.Errorf("info/exclude of ceiling not applied: %v", got)
	}
}

