// goIgnored mimics the pruning walk: each ancestor is tested as a directory.
func goIgnored(rules []ignoreRule, path string, isDir bool) bool {
	parts := strings.Split(path, "/")
	for i := 1; i < len(parts); i++ {
		if applyRules(rules, strings.Join(parts[:i], "/"), true, false) {
			return true
		}
	}
	return applyRules(rules, path, isDir, false)
}

